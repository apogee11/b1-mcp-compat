<#
.SYNOPSIS
  Compares the Service Layer files of this server with the builds covered by the connector's knowledge bases.
.DESCRIPTION
  Read-only. No credentials, no network. Prints the build id of this Service Layer and compares them with docs/covered-builds.json (generated by maintainer tooling).
  Result: COINCIDE (all files equal to a covered release), DISTINTA (same file version as a covered release but
  different hash) or NO CUBIERTA (no covered release has that version).
  It also prints the exact values to copy into the connector parameters B1McpCompat__Release and B1McpCompat__Build
  (build id: an opaque value that identifies the exact build). The Service Layer cannot tell its build: the administrator declares it.
  Exit code: 0 COINCIDE, 1 DISTINTA, 2 NO CUBIERTA, 3 error.
.PARAMETER ServiceLayerPath
  Folder of the Service Layer installation (usually ...\ServerTools\ServiceLayer).
.PARAMETER Table
  Optional path to covered-builds.json (default: docs\covered-builds.json of this repository).
#>
param(
    [Parameter(Mandatory = $true)][string]$ServiceLayerPath,
    [string]$Table
)
if (-not $Table) { $Table = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) '..\..\docs\covered-builds.json' }
$ErrorActionPreference = 'Stop'
if (-not (Test-Path -LiteralPath $Table)) { Write-Error "Table not found: $Table"; exit 3 }
if (-not (Test-Path -LiteralPath (Join-Path $ServiceLayerPath 'OBServerDLL.dll'))) {
    Write-Error "OBServerDLL.dll not found in $ServiceLayerPath"; exit 3 }
$covered = (Get-Content -LiteralPath $Table -Raw | ConvertFrom-Json).builds

function Get-FixedVersion([string]$path) {
    $v = (Get-Item -LiteralPath $path).VersionInfo
    '{0}.{1}.{2}.{3}' -f $v.FileMajorPart, $v.FileMinorPart, $v.FileBuildPart, $v.FilePrivatePart
}

# Files of this server: the ones the knowledge bases fingerprint
$local = @{}
$names = @('OBServerDLL.dll', 'B1_Engine.dll') + @(Get-ChildItem -LiteralPath $ServiceLayerPath -Filter 'B1_EnginesResources*.dll' | ForEach-Object Name)
foreach ($n in ($names | Select-Object -Unique)) {
    $p = Join-Path $ServiceLayerPath $n
    if (Test-Path -LiteralPath $p) {
        try { $local[$n] = [pscustomobject]@{ Version = Get-FixedVersion $p; Sha = (Get-FileHash -LiteralPath $p -Algorithm SHA256 -ErrorAction Stop).Hash.ToLower() } }
        catch { Write-Warning "$n cannot be read, skipped: $($_.Exception.Message)" }
    }
}
Write-Host "This server ($ServiceLayerPath):"
$local.GetEnumerator() | Sort-Object Name | ForEach-Object { Write-Host ("  {0,-34} {1,-12} {2}" -f $_.Key, $_.Value.Version, $_.Value.Sha) }

$obs = $local['OBServerDLL.dll']
function Get-BuildId {
    foreach ($n in 'OBServerDLL.dll', 'B1_Engine.dll', 'B1_EnginesResources.dll') { if (-not $local.ContainsKey($n)) { return $null } }
    '{0}-{1}-{2}-{3}' -f $obs.Version, $obs.Sha.Substring(0, 12), $local['B1_Engine.dll'].Sha.Substring(0, 12), $local['B1_EnginesResources.dll'].Sha.Substring(0, 12)
}
function Write-Params([string]$release) {
    $id = Get-BuildId
    Write-Host "`nValues for the connector (environment variables):"
    if ($release) { Write-Host "  B1McpCompat__Release = $release" } else { Write-Host '  B1McpCompat__Release = <release of your Service Layer, e.g. 2608>' }
    if ($id) { Write-Host "  B1McpCompat__Build   = $id" } else { Write-Host '  B1McpCompat__Build   = (cannot be computed: OBServerDLL.dll, B1_Engine.dll or B1_EnginesResources.dll is missing)' }
}
$byVersion = @($covered | Where-Object { ($_.files | Where-Object { $_.name -eq 'OBServerDLL.dll' }).fileVersion -eq $obs.Version })
if ($byVersion.Count -eq 0) {
    Write-Host "`nNO CUBIERTA (NOT COVERED): file version $($obs.Version) is not in the table ($(($covered | ForEach-Object release) -join ', '))."
    Write-Params $null
    Write-Host 'Send this output to the maintainer of the repository so the knowledge base for your build is generated (docs/guides/check-your-build.md).'
    exit 2
}
# A release can have several covered packages (base and hotfixes) with the same file version: the one whose hashes all match wins
function Get-Diff($b) {
    $d = @()
    foreach ($f in $b.files) {
        $l = $local[$f.name]
        if ($null -eq $l) { if ($f.name -in 'OBServerDLL.dll', 'B1_Engine.dll', 'B1_EnginesResources.dll') { $d += "$($f.name): missing on this server" }; continue }
        if ($l.Sha -ne $f.sha256) { $d += "$($f.name): hash differs (server $($l.Sha), covered $($f.sha256))" }
    }
    $d
}
$rel = $byVersion | Where-Object { @(Get-Diff $_).Count -eq 0 } | Select-Object -First 1
if (-not $rel) { $rel = $byVersion[0] }
$relNum = $rel.release -replace '^FP', ''
$diff = @(Get-Diff $rel)
if ($diff.Count -eq 0) {
    Write-Host "`nCOINCIDE (MATCH): this build is the one the knowledge base of $($rel.package) was extracted from."
    Write-Params $relNum
    exit 0
}
Write-Host "`nDISTINTA (DIFFERENT): same file version as $($rel.release) but not the same files (another patch level)."
$diff | ForEach-Object { Write-Host "  - $_" }
Write-Params $relNum
Write-Host 'This build has no knowledge base. Send this output to the maintainer (docs/guides/check-your-build.md); until then the connector refuses it unless B1McpCompat__AllowUnsupportedBuild=true.'
exit 1
